// يضمن أن اسم حزمة Flutter مطابق لما يتوقعه flutter create
export function normalizePubspec(text, dartName) {
  const base = text && /^name:/m.test(text) ? text : `name: ${dartName}\ndescription: App\npublish_to: 'none'\nversion: 1.0.0+1\n\nenvironment:\n  sdk: '>=3.3.0 <4.0.0'\n\ndependencies:\n  flutter:\n    sdk: flutter\n  http: ^1.2.2\n\nflutter:\n  uses-material-design: true\n`;
  return base.replace(/^name:.*$/m, `name: ${dartName}`);
}

// كل ملفات التطبيق النهائية: ملفات الذكاء الاصطناعي + الهيكل + الإعدادات
export function assembleApp(project, app, backendCfg) {
  const { stack } = project;
  const files = { ...scaffold(stack, project, app), ...app.files };
  files[configPath(stack, project, app)] = configFile(stack, project, app, backendCfg);
  if (stack === 'flutter') files['pubspec.yaml'] = normalizePubspec(files['pubspec.yaml'], ids(project, app).dartName);
  return files;
}

// ---------- GitHub Actions ----------
function wfHeader(project, app, id) {
  return `name: "Build ${project.slug} / ${app.id}"
on:
  workflow_dispatch:
permissions:
  contents: write
concurrency:
  group: build-${project.slug}-${app.id}
  cancel-in-progress: true
jobs:
  build:
    runs-on: ubuntu-22.04
    env:
      TAG: ${id.tagPrefix}\${{ github.run_number }}
    defaults:
      run:
        working-directory: ${id.dir}
    steps:
      - uses: actions/checkout@v4
`;
}

function wfPublish(id, apkPath, appName) {
  return `      - uses: actions/upload-artifact@v4
        with:
          name: ${id.tagPrefix}\${{ github.run_number }}
          path: ${id.dir}/${apkPath}
      - uses: softprops/action-gh-release@v2
        with:
          tag_name: \${{ env.TAG }}
          name: "${appName} — build \${{ github.run_number }}"
          files: ${id.dir}/${apkPath}
`;
}

const JAVA17 = `      - uses: actions/setup-java@v4
        with:
          distribution: temurin
          java-version: '17'
`;

export function workflow(project, app) {
  const id = ids(project, app);
  const head = wfHeader(project, app, id);
  switch (project.stack) {
    case 'html':
    case 'react':
      return head + `      - uses: actions/setup-node@v4
        with:
          node-version: '20'
${JAVA17}      - run: npm install --no-audit --no-fund
${project.stack === 'react' ? '      - run: npm run build\n' : ''}      - run: npx cap add android
      - run: npx cap sync android
      - run: chmod +x gradlew && ./gradlew assembleDebug --no-daemon
        working-directory: ${id.dir}/android
      - run: cp android/app/build/outputs/apk/debug/app-debug.apk app.apk
` + wfPublish(id, 'app.apk', id.displayName);
    case 'flutter':
      return head + `${JAVA17}      - uses: subosito/flutter-action@v2
        with:
          channel: stable
          cache: true
      - run: flutter create --platforms=android --org ${id.org} --project-name ${id.dartName} .
      - name: Internet permission + app label
        run: |
          M=android/app/src/main/AndroidManifest.xml
          grep -q 'android.permission.INTERNET' $M || sed -i '0,/<application/s//<uses-permission android:name="android.permission.INTERNET"\\/>\\n    <application/' $M
          sed -i 's#android:label="[^"]*"#android:label="${id.displayName}"#' $M
      - run: flutter pub get
      - run: flutter build apk --release
      - run: cp build/app/outputs/flutter-apk/app-release.apk app.apk
` + wfPublish(id, 'app.apk', id.displayName);
    case 'kotlin':
      return head + `${JAVA17}      - uses: gradle/actions/setup-gradle@v4
        with:
          gradle-version: '8.9'
      - run: gradle assembleDebug --no-daemon
      - run: cp app/build/outputs/apk/debug/app-debug.apk app.apk
` + wfPublish(id, 'app.apk', id.displayName);
    case 'python':
      return head + `      - uses: actions/setup-python@v5
        with:
          python-version: '3.11'
${JAVA17}      - uses: actions/cache@v4
        with:
          path: ~/.buildozer
          key: buildozer-\${{ runner.os }}-\${{ hashFiles('${id.dir}/buildozer.spec') }}
      - run: |
          sudo apt-get update
          sudo apt-get install -y git zip unzip autoconf automake libtool pkg-config zlib1g-dev libncurses5-dev libncursesw5-dev cmake libffi-dev libssl-dev
          pip install --upgrade pip buildozer "cython<3"
      - run: yes | buildozer -v android debug
      - run: cp bin/*.apk app.apk
` + wfPublish(id, 'app.apk', id.displayName);
    default: throw new Error(project.stack);
  }
}
