// تعريف لغات/أطر البناء: الهيكل الثابت، ملف الإعدادات، المسارات المسموحة للذكاء الاصطناعي، وسير عمل GitHub Actions.

export const STACKS = {
  html: { label: 'HTML / CSS / JS', web: true, entry: 'www/index.html' },
  react: { label: 'React (Vite)', web: true, entry: 'src/main.jsx' },
  flutter: { label: 'Flutter (Dart)', web: false, entry: 'lib/main.dart' },
  kotlin: { label: 'Kotlin (Jetpack Compose)', web: false, entry: 'app/src/main/java/…/MainActivity.kt' },
  python: { label: 'Python (Kivy)', web: false, entry: 'main.py' },
};

// ---------- أسماء ومعرّفات ----------
const alnum = (s) => String(s).toLowerCase().replace(/[^a-z0-9]/g, '');
const startLetter = (s, p = 'a') => (/^[a-z]/.test(s) ? s : p + s);

export function ids(project, app) {
  const slugPart = startLetter(alnum(project.slug) || 'app');
  const appPart = startLetter(alnum(app.id) || 'main');
  const pkg = `com.apkforge.${slugPart}.${appPart}`;
  return {
    pkg,
    org: `com.apkforge.${slugPart}`,
    dartName: startLetter(`${slugPart}_${appPart}`),
    pyName: appPart,
    dir: `projects/${project.slug}/${app.id}`,
    workflow: `build-${project.slug}-${app.id}.yml`,
    tagPrefix: `${project.slug}-${app.id}-b`,
    displayName: String(app.name || project.name || 'App').replace(/["'#&<>\\`$]/g, '').trim() || 'App',
  };
}

// ---------- ملف إعدادات الربط (يولّده النظام، لا الذكاء الاصطناعي) ----------
export function configPath(stack, project, app) {
  switch (stack) {
    case 'html': return 'www/config.js';
    case 'react': return 'src/config.js';
    case 'flutter': return 'lib/config.dart';
    case 'kotlin': return `app/src/main/java/${ids(project, app).pkg.replace(/\./g, '/')}/Config.kt`;
    case 'python': return 'config.py';
    default: throw new Error(`لغة غير معروفة: ${stack}`);
  }
}

const q = (v) => JSON.stringify(String(v ?? ''));
const qInterp = (v) => q(v).replace(/\$/g, '\\$'); // Dart/Kotlin: منع الاستبدال داخل النصوص

export function configFile(stack, project, app, b) {
  const v = {
    backend: b.type || 'none', supabaseUrl: b.supabaseUrl || '', supabaseAnonKey: b.supabaseAnonKey || '',
    firebaseDbUrl: b.firebaseDbUrl || '', firebaseApiKey: b.firebaseApiKey || '',
    appId: app.id, appName: app.name || '', projectName: project.name || '',
  };
  const header = 'Generated by APK Forge — do not edit. القيم عامة (anon/public) فقط.';
  switch (stack) {
    case 'html':
      return `// ${header}\nwindow.APP_CONFIG = ${JSON.stringify(v, null, 2)};\n`;
    case 'react':
      return `// ${header}\nconst config = ${JSON.stringify(v, null, 2)};\nexport default config;\n`;
    case 'flutter':
      return `// ${header}\nclass AppConfig {\n${Object.entries(v).map(([k, x]) => `  static const String ${k} = ${qInterp(x)};`).join('\n')}\n}\n`;
    case 'kotlin':
      return `// ${header}\npackage ${ids(project, app).pkg}\n\nobject Config {\n${Object.entries(v).map(([k, x]) => `    const val ${k.replace(/[A-Z]/g, (c) => '_' + c).toUpperCase()} = ${qInterp(x)}`).join('\n')}\n}\n`;
    case 'python':
      return `# ${header}\n${Object.entries(v).map(([k, x]) => `${k.replace(/[A-Z]/g, (c) => '_' + c).toUpperCase()} = ${q(x)}`).join('\n')}\n`;
    default: throw new Error(stack);
  }
}

// ---------- المسارات التي يُسمح للذكاء الاصطناعي بكتابتها ----------
export function isAllowedPath(stack, p, project, app) {
  if (p === configPath(stack, project, app)) return false;
  if (p === 'preview/index.html') return !STACKS[stack].web;
  switch (stack) {
    case 'html': return p.startsWith('www/');
    case 'react': return p === 'index.html' || p.startsWith('src/') || p.startsWith('public/');
    case 'flutter': return p === 'pubspec.yaml' || p.startsWith('lib/') || p.startsWith('assets/');
    case 'kotlin': return p.startsWith(`app/src/main/java/${ids(project, app).pkg.replace(/\./g, '/')}/`);
    case 'python': return (/^[\w-]+\.(py|kv|json)$/.test(p) && p !== 'buildozer.spec') || p.startsWith('assets/');
    default: return false;
  }
}

